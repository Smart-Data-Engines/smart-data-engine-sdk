def _model() -> sde.LogicalModel:
    return model_from_neutral(MODEL)


def _layout(entity: str, dialect: str, **design: Any) -> dict[str, Any]:
    columns = CLICKHOUSE_COLUMNS if dialect == "clickhouse" else POSTGRES_COLUMNS
    return {
        "tables": {entity: TABLES[entity]},
        "columns": {entity: dict(columns[entity])},
        **design,
    }


def _map(sources: dict[str, dict[str, Any]], *, contract: int = 5) -> dict[str, Any]:
    """A valid unsigned map placing each of the four groups on its own source."""
    model = _model()
    groups: dict[str, Any] = {}
    for group in sde.colocation_groups(model):
        (entity,) = group.members
        source = sources.get(entity) or {
            "id": f"{entity}@pg",
            "engine": "pg-main",
            "layout": _layout(entity, "postgres"),
        }
        groups[group.name] = {"source": source, **({"write_epoch": 1} if contract >= 4 else {})}
    document: dict[str, Any] = {
        "contract": contract,
        "model_version": model.version,
        "map_version": 1,
        "groups": groups,
    }
    if contract >= 4:
        document["project_id"] = PROJECT
    return document


def _source(entity: str, engine: str, dialect: str, **design: Any) -> dict[str, Any]:
    suffix = {"clickhouse": "ch", "orderbook": "ob", "postgres": "pg"}[dialect]
    return {
        "id": f"{entity}@{suffix}",
        "engine": engine,
        "layout": _layout(entity, dialect, **design),
    }


def _write(directory: Path, files: dict[str, Any]) -> None:
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    for name, body in files.items():
        (directory / name).write_text(json.dumps(body, indent=2, ensure_ascii=True) + "\n")



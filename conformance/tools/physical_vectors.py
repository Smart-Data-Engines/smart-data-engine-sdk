# --- errors/ ---------------------------------------------------------------------------------


def _refusal(name: str, document: dict[str, Any], match: str, why: str) -> str:
    model = _model()
    try:
        sde.load_map(document, model=model)
    except MapError as exc:
        assert match in str(exc), (name, match, str(exc))
    else:
        raise AssertionError(f"{name}: the reference accepted the map")
    _write(
        VECTORS / "errors" / name,
        {
            "model.json": sde.neutral_declaration(model),
            "map.json": document,
            "expected.json": {"error": "MapError", "match": match, "stage": "map", "why": why},
        },
    )
    return "errors/" + name[:3]


def _reading(contract: int = 5, **design: Any) -> dict[str, Any]:
    return _map({"Reading": _source("Reading", "ch-1", "clickhouse", **design)}, contract=contract)


def _index(**fields: Any) -> dict[str, Any]:
    return {"entity": "Reading", "name": "reading_index", "columns": ["temperature"], **fields}



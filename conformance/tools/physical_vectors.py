def _render(document: dict[str, Any], materialization: str, dialect: str) -> list[str] | Exception:
    model = _model()
    placement = sde.load_map(document, model=model)
    for group in placement.groups.values():
        for material in group.all():
            if material.id == materialization:
                keys = {entity: list(model.entity(entity).key) for entity in material.layout.tables}
                try:
                    return list(sde.schema_statements(material.layout, keys=keys, dialect=dialect))
                except EngineError as exc:
                    return exc
    raise AssertionError(f"no materialisation {materialization!r}")


def _case(
    document: dict[str, Any], materialization: str, dialect: str, why: str, **refusal: str
) -> dict[str, Any]:
    rendered = _render(document, materialization, dialect)
    case: dict[str, Any] = {
        "materialization": materialization,
        "dialect": dialect,
        "fixed": sde.schema_is_fixed(dialect),
    }
    if refusal:
        assert isinstance(rendered, EngineError), (materialization, dialect, rendered)
        assert refusal["match"] in str(rendered), (refusal["match"], str(rendered))
        case.update(error="EngineError", match=refusal["match"])
    else:
        assert isinstance(rendered, list), (materialization, dialect, rendered)
        case["statements"] = rendered
    case["why"] = why
    return case



"""Generate the physical design vectors of placement map contract 5.

Contract 5 lets a layout carry a key order, a time partition and index methods. Two libraries that
parse those keys differently build different tables from one signed document, and nothing raises -
each of them created a table successfully. So every rule gets a shared case, in the two families
that can reach it:

- ``schema/014``-``018``: the DDL a designed layout renders to, byte for byte, in both dialects,
  plus the renderer's refusals of a design made for another dialect. A map carries no dialect
  (§7), so "a BRIN index rendered for ClickHouse" is legal to load and refused where the dialect is
  known - the renderer - and nowhere earlier.
- ``errors/052``-``072``: the map-stage refusals, each with the one defect it names.

The statements come from the reference implementation, with the usual limitation - generated by
the thing they verify - and the ``schema/`` family's mitigation: ``test_schema_vectors_live.py``
executes every statement against a real PostgreSQL and a real ClickHouse, so a vector whose bytes
no engine accepts cannot be frozen.

This tool writes only the directories it names and never touches another vector. Rerunning it
rewrites exactly those, which is how a change to one of them is reviewed as a diff.

    python conformance/tools/physical_vectors.py --i-am-changing-the-contract
"""


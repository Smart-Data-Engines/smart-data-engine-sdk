"""Generate the ``schema/`` vectors: a layout in, the exact DDL out.

Section 10 of the format contract recorded this family as missing, and said why the gap was
tolerable: *"The gap costs nothing while one library claims those tiers and everything on the day
two do, so the vectors are written before a second claim is accepted, not after."* This is that day.
Raising TypeScript to Tier 2 is the second claim, so the family exists before the claim, not after
it.

What it pins, and each of these is a way two libraries can agree on a map and disagree on a
database:

- **column order**, which is code point order and not the platform's string order. This is the
  second call site of the comparator that produced the ``canonical/`` family; the first was object
  keys in the IR. ``003`` is the case no ASCII layout can reach.
- **key order**, which is *declared* order and never sorted, because in ClickHouse it becomes
  ``ORDER BY`` and decides which prefixes prune granules.
- **the refusals**: an unknown dialect, an index in a dialect with no B-tree, a key naming a column
  the layout does not have, a layout with no columns, and a caller that supplied no key.
- **which engines take DDL from us at all**, through ``fixed`` on every case.

The statements come from the reference implementation, with the usual limitation - generated by the
thing they verify - and one mitigation that the other families do not have:
``python/tests/test_schema_vectors_live.py`` executes every statement in this family against a real
PostgreSQL and a real ClickHouse. A vector whose bytes no engine accepts would be a frozen mistake,
and that test is what makes it impossible.

    python conformance/tools/schema_vectors.py --i-am-changing-the-contract
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python" / "src"))

import sde  # noqa: E402
from sde.errors import EngineError  # noqa: E402
from sde.testing.loader import model_from_neutral  # noqa: E402

VECTORS = ROOT / "conformance" / "vectors" / "schema"


def _neutral(model: sde.LogicalModel) -> dict[str, Any]:
    return sde.neutral_declaration(model)


def _layout_doc(layout: sde.PhysicalLayout) -> dict[str, Any]:
    doc: dict[str, Any] = {
        "tables": dict(layout.tables),
        "columns": {e: dict(c) for e, c in layout.columns.items()},
    }
    if layout.indexes:
        doc["indexes"] = [dict(i) for i in layout.indexes]
    return doc


def _map(model: sde.LogicalModel, materializations: dict[str, dict[str, Any]]) -> dict[str, Any]:
    """A minimal, valid, unsigned map placing every group with one source each.

    A whole map rather than a bare layout document, and that is the decision worth stating: the
    input then reaches the renderer through the *same* loader production uses, instead of through a
    second parser written for the vectors. It also means a case can only pin DDL for a layout this
    library would accept in the first place.
    """
    groups: dict[str, Any] = {}
    for group in sde.colocation_groups(model):
        spec = materializations[group.name]
        groups[group.name] = {"source": spec}
    return {
        "contract": sde.CONTRACT,
        "model_version": model.version,
        "map_version": 1,
        "groups": groups,
    }


def _write(name: str, model: sde.LogicalModel, raw_map: dict[str, Any], cases: list[Any]) -> None:
    out = VECTORS / name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / "model.json").write_text(json.dumps(_neutral(model), indent=2) + "\n", encoding="utf-8")
    (out / "map.json").write_text(json.dumps(raw_map, indent=2) + "\n", encoding="utf-8")
    (out / "cases.json").write_text(json.dumps(cases, indent=2) + "\n", encoding="utf-8")
    print(f"  wrote schema/{name}")


def _shop() -> sde.LogicalModel:
    """Two entities in one colocation group, one of them with a composite key and a relation.

    Declared neutrally rather than through the decorator so that the field order in the document is
    the one written here - which is *not* sorted, so a library that trusted the document's order
    instead of sorting would produce different DDL and this family would catch it.
    """
    sde.clear_registry()
    return model_from_neutral(
        {
            "entities": [
                {
                    "name": "Order",
                    "fields": [
                        {"name": "tenant", "type": "uuid"},
                        {"name": "id", "type": "uuid"},
                        {"name": "total", "type": "decimal(12,2)"},
                        {"name": "placed_at", "type": "timestamptz"},
                    ],
                    "key": ["tenant", "id"],
                    "residency": "EU",
                },
                {
                    "name": "Payment",
                    "fields": [
                        {"name": "id", "type": "uuid"},
                        {"name": "amount", "type": "decimal(12,2)"},
                        {"name": "paid_at", "type": "timestamp"},
                    ],
                    "key": ["id"],
                },
            ],
            "relations": [{"name": "order", "from": "Payment", "to": "Order"}],
            "atomic": [["Order", "Payment"]],
        }
    )


def _astral() -> sde.LogicalModel:
    """Column names that expose UTF-16 order against code point order.

    Above U+FFFF the two disagree: an astral character is a surrogate pair starting at 0xD800, so
    UTF-16 order puts it *before* U+E000 while code point order puts it after. Every layout in this
    family other than this one is ASCII, and no ASCII layout can tell the two comparators apart.
    """
    sde.clear_registry()
    return model_from_neutral(
        {
            "entities": [
                {
                    "name": "Astral",
                    "fields": [
                        {"name": "id", "type": "uuid"},
                        {"name": "a", "type": "string"},
                        {"name": "\U0001f600", "type": "string"},
                        {"name": "\ue000", "type": "string"},
                    ],
                    "key": ["id"],
                }
            ],
            "relations": [],
            "atomic": [],
        }
    )


def _orderbook() -> sde.LogicalModel:
    """The one shape our own orderbook engine stores, declared as a model.

    Not a coincidence that it reads like the engine's own header: the relationship inverts for a
    fixed-schema engine, so either the client's model *is* this shape or the group cannot be placed
    there at all.
    """
    sde.clear_registry()
    return model_from_neutral(
        {
            "entities": [
                {
                    "name": "Depth",
                    "fields": [
                        {"name": name, "type": kind}
                        for name, kind in sde.ORDERBOOK_SHAPE.items()
                    ],
                    "key": list(sde.ORDERBOOK_KEY),
                }
            ],
            "relations": [],
            "atomic": [],
        }
    )


def _statements(layout: sde.PhysicalLayout, model: sde.LogicalModel, group: str, dialect: str):
    members = next(g for g in sde.colocation_groups(model) if g.name == group)
    keys = {name: list(model.entity(name).key) for name in members.members}
    return list(sde.schema_statements(layout, keys=keys, dialect=dialect))


def _refusal(fn: Any, match: str) -> dict[str, str]:
    """Check that the reference refuses, and that its message contains ``match``.

    The vector stores the substring rather than the whole sentence, exactly as the ``errors/``
    family does: a library may say more, in any language it likes, and may not say less. Written as
    a check rather than a capture so that the substring in the vector is one a person chose, and so
    that generating this family cannot quietly record a *different* refusal than the one intended.
    """
    try:
        fn()
    except EngineError as exc:
        if match not in str(exc):
            raise SystemExit(f"the reference refused with {str(exc)!r}, which does not contain {match!r}")
        return {"error": "EngineError", "match": match}
    raise SystemExit(f"expected a refusal containing {match!r} and got none")


def _one() -> None:
    model = _shop()
    group = "Order"
    pg = sde.default_layout(model, next(g for g in sde.colocation_groups(model) if g.name == group))
    raw = _map(model, {group: {"id": "Order@pg", "engine": "pg-main", "layout": _layout_doc(pg)}})
    cases = [
        {
            "materialization": "Order@pg",
            "dialect": "postgres",
            "fixed": False,
            "statements": _statements(pg, model, group, "postgres"),
            "why": (
                "Columns are sorted by name and the key is not: 'tenant' comes before 'id' in the "
                "PRIMARY KEY because that is the order the model declared, and a sorted key would "
                "silently reorder a composite index. The tables come out in code point order of "
                "the entity name, which is why 'Order' precedes 'Payment' here and why a library "
                "iterating the document's own order would drift the day a planner emitted them "
                "differently."
            ),
        },
        {
            "materialization": "Order@pg",
            "dialect": "clickhouse",
            "fixed": False,
            **_refusal(lambda: _statements(pg, model, group, "clickhouse"), "no B-tree to put them in"),
            "why": (
                "The fifth issuing rule, from the library's side. A layout carrying an index is "
                "valid, signs correctly and loads correctly, and rendering it for an engine with "
                "no B-tree is where it stops being applicable - a map that verifies and cannot be "
                "applied. The control plane asks this library rather than reimplementing the "
                "answer, so this refusal is what stops such a map being issued at all."
            ),
        },
    ]
    _write("001-postgres-a-group-of-two-entities", model, raw, cases)



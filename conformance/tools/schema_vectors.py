def _six() -> None:
    """A key column the layout does not have, and a layout with no columns at all."""
    model = _shop()
    group = "Order"
    members = next(g for g in sde.colocation_groups(model) if g.name == group)
    ch = sde.default_layout(model, members, dialect="clickhouse")
    keys = {name: list(model.entity(name).key) for name in members.members}

    thin_columns = {e: dict(c) for e, c in ch.columns.items()}
    del thin_columns["Order"]["tenant"]
    thin = sde.PhysicalLayout(tables=dict(ch.tables), columns=thin_columns, indexes=())

    empty = sde.PhysicalLayout(tables=dict(ch.tables), columns={}, indexes=())

    raw = _map(model, {group: {"id": "Order@ch", "engine": "ch-1", "layout": _layout_doc(thin)}})
    cases = [
        {
            "materialization": "Order@ch",
            "dialect": "clickhouse",
            "fixed": False,
            **_refusal(
                lambda: sde.schema_statements(thin, keys=keys, dialect="clickhouse"),
                "names columns the layout does not have",
            ),
            "why": (
                "The key becomes ORDER BY, so a key column that is not in the table is a statement "
                "that will not parse - refused here rather than by the engine, because the engine's "
                "message names a column and not the cause. PostgreSQL would refuse the same layout "
                "for its own reason; the two are separate refusals because ORDER BY and PRIMARY "
                "KEY are separate mechanisms."
            ),
        },
        {
            "materialization": "Order@ch",
            "dialect": "clickhouse",
            "fixed": False,
            "layout_columns": {},
            **_refusal(
                lambda: sde.schema_statements(empty, keys=keys, dialect="clickhouse"),
                "gives no columns for",
            ),
            "why": (
                "A layout with tables and no columns is not a layout this library can apply. It is "
                "reachable: `columns` is optional in the document because the routing families do "
                "not need it, so a hand-written map naming tables alone loads cleanly and fails "
                "here. `layout_columns` replaces the materialisation's columns in the runner, "
                "which is the one place a case edits its own input - there is no other way to "
                "express 'the map said nothing about columns' once the loader has parsed it."
            ),
        },
    ]
    _write("006-a-key-column-the-layout-does-not-have", model, raw, cases)



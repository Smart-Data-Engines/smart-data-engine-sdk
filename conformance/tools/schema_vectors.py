def _eight() -> None:
    """Compatibility views: what can stand under a table's old name, and what cannot."""
    model = _shop()
    group = "Order"
    members = next(g for g in sde.colocation_groups(model) if g.name == group)
    pg = sde.default_layout(model, members)
    ch = sde.default_layout(model, members, dialect="clickhouse")
    raw = _map(model, {group: {"id": "Order@pg", "engine": "pg-main", "layout": _layout_doc(pg)}})
    raw["groups"][group]["derived"] = [
        {"id": "Order@ch", "engine": "ch-1", "layout": _layout_doc(ch), "lag_budget_ms": 30000}
    ]

    renamed = {"Order": "orders_v1", "Payment": "payments_v1"}
    same = dict(pg.tables)

    def views(
        layout: sde.PhysicalLayout,
        was: dict[str, str],
        dialect: str,
        expect: dict[str, list[str]],
    ) -> dict[str, Any]:
        """The rendered views, with the *reasons* pinned as substrings a person chose.

        `create` and `drop` are statements - bytes an engine receives - so they are pinned exactly.
        A reason is diagnostics, so it is pinned the way the `errors/` family pins a message: a
        library may say more, in any language it likes, and may not say less. `match` is a list
        here because the useful reasons carry two claims - which name moved, and what the query has
        to become - and one substring cannot straddle both.
        """
        result = sde.compatibility_views(layout, was=was, dialect=dialect)
        got = {entity: why for entity, why in result.not_possible}
        if sorted(got) != sorted(expect):
            raise SystemExit(f"not_possible is {sorted(got)}, the case expects {sorted(expect)}")
        for entity, wanted in expect.items():
            for fragment in wanted:
                if fragment not in got[entity]:
                    raise SystemExit(f"{entity}: {got[entity]!r} does not contain {fragment!r}")
        return {
            "create": list(result.create),
            "drop": list(result.drop),
            "not_possible": [
                {"entity": entity, "match": expect[entity]} for entity, _ in result.not_possible
            ],
            "complete": result.complete,
        }

    cases = [
        {
            "materialization": "Order@pg",
            "dialect": "postgres",
            "fixed": False,
            "statements": _statements(pg, model, group, "postgres"),
            "views": {"was": renamed, **views(pg, renamed, "postgres", {})},
            "why": (
                "The tables were called something else in the engine the group left, so a view can "
                "stand under each old name. CREATE OR REPLACE VIEW, because PostgreSQL has no "
                "CREATE VIEW IF NOT EXISTS - measured against the server, and the first draft of "
                "the renderer emitted the form that is a syntax error. Columns are listed rather "
                "than SELECT *, in the layout's order, so a query reading them by position sees "
                "what CREATE TABLE produced."
            ),
        },
        {
            "materialization": "Order@ch",
            "dialect": "clickhouse",
            "fixed": False,
            "statements": _statements(ch, model, group, "clickhouse"),
            "views": {
                "was": same,
                **views(
                    ch,
                    same,
                    "clickhouse",
                    {
                        "Order": ["the name is not what moved", "FINAL", "counted twice"],
                        "Payment": ["the name is not what moved", "FINAL"],
                    },
                ),
            },
            "why": (
                "Both engines derive the table name from the entity name and nothing else, so "
                "after a move between them the name is not what changed - the dialect is, and "
                "there is no old name for a view to occupy. That is the ordinary answer in this "
                "engine set, and the useful part of it is the sentence: a query moved here "
                "verbatim must read FINAL, because the table is a ReplacingMergeTree and without "
                "it a row written twice under one key is counted twice until a background merge - "
                "measured, two rows against one."
            ),
        },
    ]
    _write("008-compatibility-views-on-the-target", model, raw, cases)


def _nine() -> None:
    """A document whose columns are out of order, and both renderings sorted anyway.

    The case that makes the two sorts separately mutable. Before this vector the view renderer read
    its column order off the document, on the stated grounds that the document was already sorted -
    it is not, because a foreign-key column is appended per relation - so an entity with a relation
    had a view and a table listing the same columns in different orders, and a hand-written query
    moved onto the view read them by position and got different values. The test meant to hold that
    property used a fixture with no relations.
    """
    model = _shop()
    group = "Order"
    members = next(g for g in sde.colocation_groups(model) if g.name == group)
    pg = sde.default_layout(model, members)
    doc = _layout_doc(pg)
    # Reversed on purpose. A planner emits them in one order; a client hand-writing a map in the
    # no-account mode emits whatever they typed, and both must produce one database.
    doc["columns"] = {e: dict(reversed(list(c.items()))) for e, c in doc["columns"].items()}
    raw = _map(model, {group: {"id": "Order@pg", "engine": "pg-main", "layout": doc}})

    scrambled = sde.PhysicalLayout(
        tables=dict(pg.tables),
        columns={e: dict(reversed(list(c.items()))) for e, c in pg.columns.items()},
        indexes=tuple(dict(i) for i in pg.indexes),
    )
    renamed = {"Order": "orders_v1", "Payment": "payments_v1"}
    result = sde.compatibility_views(scrambled, was=renamed, dialect="postgres")
    cases = [
        {
            "materialization": "Order@pg",
            "dialect": "postgres",
            "fixed": False,
            "statements": _statements(scrambled, model, group, "postgres"),
            "views": {
                "was": renamed,
                "create": list(result.create),
                "drop": list(result.drop),
                "not_possible": [],
                "complete": result.complete,
            },
            "why": (
                "Every column list here comes out sorted by name even though the document lists "
                "them reversed, and the two lists that matter are the CREATE TABLE and the view's "
                "SELECT - separate statements, so removing either sort changes a different string "
                "and neither can hide behind the other. Column *types* stay attached to their "
                "columns, which is the part a naive 'sort the values too' would get wrong."
            ),
        }
    ]
    _write("009-columns-out-of-order-in-the-document", model, raw, cases)


def _ten() -> None:
    """One model with every type both engines map, and both layouts in one map.

    Two jobs. As a schema vector it pins the DDL for the whole neutral vocabulary minus the two
    types ClickHouse deliberately has no column for. And as a fixture it is what the TypeScript
    library's engine-agreement test round-trips through: the same value written through both
    adapters has to come back identical in content **and** in JavaScript type, and the layouts it
    writes against have to be the ones a planner would issue rather than ones a test typed out.

    `bytes` and `json` are absent on purpose. ClickHouse has no column for them in this library, so
    `default_layout` refuses that dialect for a group containing one - which is the mechanism that
    stops a planner placing such a group there, and it is checked by its own test rather than here.
    """
    sde.clear_registry()
    model = model_from_neutral(
        {
            "entities": [
                {
                    "name": "Sample",
                    "fields": [
                        {"name": "id", "type": "uuid"},
                        {"name": "label", "type": "string"},
                        {"name": "small", "type": "int32"},
                        {"name": "big", "type": "int64"},
                        {"name": "approx", "type": "float64"},
                        {"name": "narrow", "type": "float32"},
                        {"name": "money", "type": "decimal(12,2)"},
                        {"name": "flag", "type": "bool"},
                        {"name": "at", "type": "timestamptz"},
                        {"name": "naive", "type": "timestamp"},
                        {"name": "day", "type": "date"},
                    ],
                    "key": ["id"],
                }
            ],
            "relations": [],
            "atomic": [],
        }
    )

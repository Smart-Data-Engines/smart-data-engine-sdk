/// The reference's fixture: one row in each engine, the copy's value different from the source's,
/// and a request for the map the session holds.
struct Bound {
  Bound()
      : model(sde::load_neutral_model(R"({"entities": [{"name": "Event", "fields": [
          {"name": "id", "type": "int32"}, {"name": "value", "type": "string"}],
          "key": ["id"]}]})")),
        document(sde::parse_json(R"({"contract": 3, "model_version": ")" + model.version() +
                                 R"(", "map_version": 1, "groups": {"Event": {
          "source": {"id": "source", "engine": "source", "layout": {"tables": {"Event": "events"},
                     "columns": {"Event": {"id": "integer", "value": "text"}}}},
          "derived": [{"id": "copy", "engine": "copy", "lag_budget_ms": 1000,
                       "layout": {"tables": {"Event": "events_copy"},
                                  "columns": {"Event": {"id": "integer", "value": "text"}}}}],
          "also_write": ["copy"]}}})")),
        map(load(document)),
        source(holding("source", "events", "private-row-value")),
        target(holding("copy", "events_copy", "different-private-value")),
        request(sde::verification_request(map, "Event", kProject, kRequest, kAt)) {}

  /// An engine on the shared journal, holding one row of the table.
  sde::testing::MemoryEngineOptions holding(std::string name, const std::string& table,
                                            const std::string& value) const {
    sde::testing::MemoryEngineOptions options;
    options.name = std::move(name);
    options.journal = journal;
    options.tables[table] = {sde::Row{{"id", std::int64_t{729381}}, {"value", value}}};
    return options;
  }
  sde::PlacementMap load(const sde::Json& raw) const {
    sde::LoadOptions options;
    options.model = &model;
    return sde::load_map(raw, options);
  }
  sde::Session session(std::optional<std::string> project = kProject) {
    sde::SessionOptions options;
    options.project_id = std::move(project);
    return sde::Session(model, map, {{"source", &source}, {"copy", &target}}, options);
  }

  sde::Model model;
  sde::Json document;
  sde::PlacementMap map;
  std::shared_ptr<sde::testing::Recorded> journal = std::make_shared<sde::testing::Recorded>();
  sde::testing::MemoryEngine source;
  sde::testing::MemoryEngine target;
  sde::VerificationRequest request;
};

TEST(VerificationRequest, TheRecordCarriesTheRequestAndNoRowValue) {
  Bound bound;
  sde::Session session = bound.session();
  sde::VerifyOptions options;
  options.request = bound.request;
  const sde::VerifyReport result = sde::verify(session, "Event", options);
  EXPECT_FALSE(result.matched());
  EXPECT_EQ(result.request, bound.request);
  EXPECT_EQ(*result.as_record().find("request"), bound.request.as_record());
  EXPECT_EQ(result.differences.at(0).key, (sde::Row{{"id", std::int64_t{729381}}}));
  const std::string encoded = sde::canonical_bytes(result.as_record());
  EXPECT_FALSE(contains(encoded, "private-row-value"));
  EXPECT_FALSE(contains(encoded, "different-private-value"));
  EXPECT_FALSE(contains(encoded, "\"key\""));
  EXPECT_EQ(sde::VerificationRequest::from_record(bound.request.as_record()), bound.request);
}

/// A request's fields, to change one at a time.
struct Fields {
  explicit Fields(const sde::VerificationRequest& r)
      : request_id(r.request_id()), project_id(r.project_id()), model_version(r.model_version()),
        map_version(r.map_version()), map_fingerprint(r.map_fingerprint()), group(r.group()),
        source_engine(r.source_engine()), source_id(r.source_id()), targets(r.targets()),
        requested_at(r.requested_at()), requires_signature(r.requires_signature()) {}
  [[nodiscard]] sde::VerificationRequest request() const {
    return sde::VerificationRequest(request_id, project_id, model_version, map_version,
                                    map_fingerprint, group, source_engine, source_id, targets,
                                    requested_at, requires_signature);
  }
  std::string request_id, project_id, model_version;
  std::int64_t map_version;
  std::string map_fingerprint, group, source_engine, source_id;
  std::vector<std::pair<std::string, std::string>> targets;
  std::string requested_at;
  bool requires_signature;
};

TEST(VerificationRequest, AWrongBindingIsRefusedBeforeTheFirstEngineCall) {
  Bound bound;
  const std::vector<std::function<void(Fields&)>> edits = {
      [](Fields& f) { f.project_id = std::string(32, '3'); },
      [](Fields& f) { f.model_version = std::string(16, '0'); },
      [](Fields& f) { f.map_version = 2; },
      [](Fields& f) { f.map_fingerprint = std::string(64, '0'); },
      [](Fields& f) { f.group = "Other"; },
      [](Fields& f) { f.source_engine = "other"; },
      [](Fields& f) { f.source_id = "other-id"; },
      [](Fields& f) { f.targets = {{"other", "other-id"}}; },
      [](Fields& f) { f.requires_signature = true; },
  };
  for (const auto& edit : edits) {
    Fields fields(bound.request);
    edit(fields);
    sde::Session session = bound.session();
    sde::VerifyOptions options;
    options.request = fields.request();
    (void)refusal([&] { (void)sde::verify(session, "Event", options); });
    EXPECT_TRUE(bound.journal->calls().empty())
        << sde::canonical_bytes(options.request->as_record());
  }
}


TEST(BigUnsigned, DividesAsPythonDoes) {
  for (const DivisionCase& c : kDivisions) {
    const auto [quotient, remainder] = divmod(big(c.dividend), big(c.divisor));
    EXPECT_EQ(quotient.to_decimal(), c.quotient) << c.dividend << " // " << c.divisor;
    EXPECT_EQ(remainder.to_decimal(), c.remainder) << c.dividend << " % " << c.divisor;
  }
}

TEST(BigUnsigned, DivisionSatisfiesItsIdentity) {
  // n = q * d + r with r < d, for numbers of one to seven limbs. Multiplication and addition are
  // checked against Python separately, so this is not the division checking itself.
  std::mt19937_64 random(20261006);
  const auto limb = [&random]() -> std::uint64_t {
    switch (random() % 6) {
      case 0: return 0;
      case 1: return 0xFFFFFFFFU;
      case 2: return 0x80000000U;
      case 3: return 1;
      default: return random() & 0xFFFFFFFFU;
    }
  };
  const auto number = [&](unsigned limbs) {
    BigUnsigned out;
    for (unsigned i = 0; i < limbs; ++i) out = out * BigUnsigned(std::uint64_t{1} << 32) + BigUnsigned(limb());
    return out;
  };
  for (int round = 0; round < 20000; ++round) {
    const BigUnsigned n = number(static_cast<unsigned>(random() % 7 + 1));
    const BigUnsigned d = number(static_cast<unsigned>(random() % 5 + 1));
    if (d.is_zero()) continue;
    const auto [q, r] = divmod(n, d);
    ASSERT_LT(r, d) << n.to_decimal() << " / " << d.to_decimal();
    ASSERT_EQ(q * d + r, n) << n.to_decimal() << " / " << d.to_decimal();
  }
}

TEST(BigUnsigned, ReadsAndWritesDecimal) {
  for (const std::string digits :
       {"0", "1", "9", "10", "999999999", "1000000000", "4294967295", "4294967296",
        "18446744073709551615", "18446744073709551616",
        "123456789012345678901234567890123456789012345678901234567890123456789012345678"}) {
    EXPECT_EQ(big(digits).to_decimal(), digits);
  }
  EXPECT_EQ(big("000").to_decimal(), "0");
  EXPECT_EQ(big("0000000001").to_decimal(), "1");
  for (const std::string bad : {"", "-1", "+1", " 1", "1 ", "1a", "1.0", "\xd9\xa1"}) {
    EXPECT_FALSE(BigUnsigned::from_decimal(bad).has_value()) << bad;
  }
}

TEST(BigUnsigned, PowersOfTen) {
  for (unsigned exponent = 0; exponent <= 120; ++exponent) {
    EXPECT_EQ(BigUnsigned::pow10(exponent).to_decimal(), "1" + std::string(exponent, '0'));
  }
}

TEST(BigUnsigned, MultipliesAndAddsAsPythonDoes) {
  // (2^64 - 1)^2 and (10^40 + 7) * (10^38 + 3), from CPython.
  EXPECT_EQ((big("18446744073709551615") * big("18446744073709551615")).to_decimal(),
            "340282366920938463426481119284349108225");
  EXPECT_EQ((big("10000000000000000000000000000000000000007") *
             big("100000000000000000000000000000000000003")).to_decimal(),
            "1000000000000000000000000000000000000030700000000000000000000000000000000000021");
  EXPECT_EQ((big("4294967295") + big("1")).to_decimal(), "4294967296");
  EXPECT_EQ((big("18446744073709551615") + big("18446744073709551615")).to_decimal(),
            "36893488147419103230");
  EXPECT_EQ((big("18446744073709551616") - big("1")).to_decimal(), "18446744073709551615");
  EXPECT_EQ((big("100000000000000000000") - big("99999999999999999999")).to_decimal(), "1");
  EXPECT_EQ((big("0") * big("12345")).to_decimal(), "0");
}

TEST(BigUnsigned, ComparesAndKnowsItsParity) {
  EXPECT_LT(big("4294967295"), big("4294967296"));
  EXPECT_GT(big("18446744073709551616"), big("18446744073709551615"));
  EXPECT_EQ(big("0"), BigUnsigned{});
  EXPECT_TRUE(big("18446744073709551617").is_odd());
  EXPECT_FALSE(big("18446744073709551616").is_odd());
  EXPECT_FALSE(BigUnsigned{}.is_odd());
  EXPECT_EQ(big("18446744073709551615").to_uint64(), 18446744073709551615ULL);
  EXPECT_FALSE(big("18446744073709551616").to_uint64().has_value());
  EXPECT_THROW((void)(big("1") - big("2")), std::logic_error);
  EXPECT_THROW((void)divmod(big("1"), BigUnsigned{}), std::domain_error);
}

